/*
=== НЕБУФЕРИЗОВАННЫЕ КАНАЛЫ (UNBUFFERED CHANNELS) ===

Канал — это типизированный канал связи между горутинами.
Создание: ch := make(chan T)   // небуферизованный канал типа T

Небуферизованный канал — это СИНХРОННЫЙ обмен:
  - Отправитель (ch <- val) БЛОКИРУЕТСЯ, пока получатель не будет готов прочитать.
  - Получатель (val := <-ch) БЛОКИРУЕТСЯ, пока отправитель не отправит значение.
  Это как передача предмета из рук в руки — обе стороны должны быть на месте.

Гарантия "happens-before":
  Отправка в канал ЗАВЕРШАЕТСЯ ДО того, как соответствующее получение завершается.
  Это значит: всё, что горутина-отправитель сделала до ch <- val, видно
  горутине-получателю после val := <-ch. Канал — это точка синхронизации памяти.

Дедлок:
  Если в канал пишут, но никто не читает (или наоборот) — Go runtime обнаруживает
  deadlock и паникует: "fatal error: all goroutines are asleep - deadlock!"

nil-канал:
  var ch chan int  // ch == nil
  Чтение и запись в nil-канал блокируются НАВСЕГДА.
  Это полезно в select для динамического отключения case'ов (см. урок 06_select).
*/
package main

import (
	"fmt"
	"time"
)

func main() {
	// =====================================================
	// Пример 1: Базовая отправка и получение
	// =====================================================
	fmt.Println("=== Пример 1: Базовая отправка и получение ===")

	ch := make(chan string) // небуферизованный канал строк

	// Запускаем горутину-отправитель
	go func() {
		fmt.Println("  отправитель: готовлю данные...")
		time.Sleep(500 * time.Millisecond) // имитация работы
		ch <- "Привет из горутины!"        // блокируется, пока main не прочитает
		fmt.Println("  отправитель: данные отправлены!")
	}()

	fmt.Println("  main: жду данные из канала...")
	msg := <-ch // блокируется, пока горутина не отправит
	fmt.Printf("  main: получил: %q\n", msg)
	fmt.Println()

	// =====================================================
	// Пример 2: Канал как сигнал завершения (done channel)
	// =====================================================
	fmt.Println("=== Пример 2: Сигнал завершения (done channel) ===")

	done := make(chan struct{}) // struct{} — нулевой размер, идиоматичный сигнал

	go func() {
		fmt.Println("  worker: выполняю тяжёлую работу...")
		time.Sleep(300 * time.Millisecond)
		fmt.Println("  worker: готово!")
		done <- struct{}{} // сигнализируем о завершении
	}()

	<-done // ждём сигнала
	fmt.Println("  main: worker завершился, продолжаем.")
	fmt.Println()

	// =====================================================
	// Пример 3: Синхронность — отправитель ждёт получателя
	// =====================================================
	fmt.Println("=== Пример 3: Синхронность — обе стороны ждут друг друга ===")

	syncCh := make(chan int)

	go func() {
		fmt.Println("  отправитель: отправляю 42...")
		start := time.Now()
		syncCh <- 42 // блокируется, пока получатель не будет готов
		fmt.Printf("  отправитель: разблокирован через %v\n", time.Since(start))
	}()

	// Намеренно ждём, чтобы отправитель заблокировался
	time.Sleep(1 * time.Second)
	fmt.Println("  получатель: теперь читаю из канала...")
	val := <-syncCh
	fmt.Printf("  получатель: получил %d\n", val)

	time.Sleep(50 * time.Millisecond) // даём отправителю напечатать
	fmt.Println()

	// =====================================================
	// Пример 4: Гарантия happens-before
	// =====================================================
	fmt.Println("=== Пример 4: Гарантия happens-before ===")

	dataCh := make(chan int)
	var sharedData string // общие данные, доступ синхронизирован через канал

	go func() {
		// Всё, что происходит ДО отправки — видно получателю ПОСЛЕ получения.
		sharedData = "данные подготовлены" // запись ДО отправки
		dataCh <- 1                        // точка синхронизации
	}()

	<-dataCh // после этого sharedData гарантированно "данные подготовлены"
	fmt.Printf("  sharedData = %q (гарантированно видно благодаря каналу)\n", sharedData)
	fmt.Println()

	// =====================================================
	// Пример 5: Deadlock — демонстрация (закомментировано)
	// =====================================================
	fmt.Println("=== Пример 5: Deadlock (закомментирован, раскомментируйте для проверки) ===")
	fmt.Println("  // deadlockCh := make(chan int)")
	fmt.Println("  // deadlockCh <- 42  // DEADLOCK: никто не читает!")
	fmt.Println("  // Рантайм Go обнаружит: fatal error: all goroutines are asleep - deadlock!")
	// Раскомментируйте для проверки:
	// deadlockCh := make(chan int)
	// deadlockCh <- 42 // DEADLOCK!
	fmt.Println()

	// =====================================================
	// Пример 6: nil-канал блокируется навсегда
	// =====================================================
	fmt.Println("=== Пример 6: nil-канал ===")

	var nilCh chan int // nil канал
	fmt.Printf("  nilCh == nil: %v\n", nilCh == nil)
	fmt.Println("  Чтение/запись в nil-канал блокируется навсегда.")
	fmt.Println("  Это полезно в select для отключения case'ов (см. урок 06_select).")

	// Демонстрация: пытаемся читать с таймаутом
	go func() {
		select {
		case v := <-nilCh:
			// Этот case НИКОГДА не сработает — nil канал блокируется навсегда
			fmt.Println("  Невозможно:", v)
		case <-time.After(200 * time.Millisecond):
			fmt.Println("  [таймаут] чтение из nil-канала заблокировано навсегда, как и ожидалось.")
		}
	}()

	time.Sleep(300 * time.Millisecond)
	fmt.Println()

	// =====================================================
	// Пример 7: Несколько горутин общаются через канал
	// =====================================================
	fmt.Println("=== Пример 7: Пинг-понг через каналы ===")

	ping := make(chan string)
	pong := make(chan string)

	// Игрок 1: получает ping, отправляет pong
	go func() {
		for i := range 3 {
			msg := <-ping
			fmt.Printf("  Игрок 1: получил %q (раунд %d)\n", msg, i)
			pong <- fmt.Sprintf("понг-%d", i)
		}
	}()

	// Игрок 2 (main): отправляет ping, получает pong
	for i := range 3 {
		ping <- fmt.Sprintf("пинг-%d", i)
		msg := <-pong
		fmt.Printf("  Игрок 2: получил %q (раунд %d)\n", msg, i)
	}

	fmt.Println("\n=== Все примеры завершены ===")
}
