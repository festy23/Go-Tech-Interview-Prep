/*
=== ГОРУТИНЫ (GOROUTINES) ===

Горутина — это легковесный поток выполнения, управляемый рантаймом Go, а НЕ операционной системой.

Ключевые отличия от потоков ОС:
  - Начальный размер стека горутины: ~2-8 КБ (растёт динамически до ~1 ГБ).
    Поток ОС — фиксированный стек ~1-8 МБ. Поэтому можно создать сотни тысяч горутин.
  - Переключение контекста горутин дешевле: это user-space операция, без syscall.

Модель планирования GMP (Go's scheduler):
  - G (Goroutine) — горутина, единица работы.
  - M (Machine)   — поток ОС, на котором выполняются горутины.
  - P (Processor) — логический процессор, связывает G и M. По умолчанию P = GOMAXPROCS = кол-во ядер CPU.
  Схема: M горутин мультиплексируются на N потоков ОС (M:N модель).
  Планировщик Go сам распределяет горутины по потокам, ворует работу у других P (work stealing).

Запуск горутины:
  go someFunction()       // именованная функция
  go func() { ... }()    // анонимная функция (замыкание)

ВАЖНО: когда main-горутина завершается — ВСЕ остальные горутины немедленно умирают!
Программа не ждёт их завершения. Это одна из самых частых ошибок новичков.
*/
package main

import (
	"fmt"
	"runtime"
	"sync"
	"time"
)

func main() {
	// =====================================================
	// Пример 1: Главная горутина завершается — остальные умирают
	// =====================================================
	fmt.Println("=== Пример 1: main завершается — горутины умирают ===")
	fmt.Println("Раскомментируйте вызов deadGoroutineDemo() и закомментируйте остальное, чтобы увидеть эффект.")
	fmt.Println("(Горутина напечатает только часть сообщений или ни одного.)")
	// deadGoroutineDemo() // <-- раскомментировать для демонстрации
	fmt.Println()

	// =====================================================
	// Пример 2: Запуск горутин разными способами
	// =====================================================
	fmt.Println("=== Пример 2: Запуск горутин ===")

	var wg sync.WaitGroup

	// Способ 1: именованная функция
	wg.Add(1)
	go sayHello(&wg, "Горутина-1")

	// Способ 2: анонимная функция (замыкание)
	wg.Add(1)
	go func() {
		defer wg.Done()
		fmt.Println("  Привет из анонимной горутины!")
	}()

	// Способ 3: передача аргумента (Go 1.22 — переменные цикла безопасны!)
	for i := range 5 {
		wg.Add(1)
		// В Go 1.22 переменная i в цикле for-range НЕ расшаривается между итерациями.
		// Каждая итерация получает свою копию. Раньше (до 1.22) тут была бы ошибка.
		go func() {
			defer wg.Done()
			fmt.Printf("  Цикл горутина i=%d\n", i)
		}()
	}

	wg.Wait()
	fmt.Println()

	// =====================================================
	// Пример 3: Недетерминированный порядок выполнения
	// =====================================================
	fmt.Println("=== Пример 3: Порядок выполнения НЕ гарантирован ===")
	fmt.Println("Запустите программу несколько раз — порядок будет разным!")

	var wg2 sync.WaitGroup
	for i := range 10 {
		wg2.Add(1)
		go func() {
			defer wg2.Done()
			fmt.Printf("  горутина #%d\n", i)
		}()
	}
	wg2.Wait()
	fmt.Println()

	// =====================================================
	// Пример 4: Горутины дешёвые — запуск 100 000 штук
	// =====================================================
	fmt.Println("=== Пример 4: 100 000 горутин ===")

	start := time.Now()
	const numGoroutines = 100_000

	var wg3 sync.WaitGroup
	wg3.Add(numGoroutines)

	for range numGoroutines {
		go func() {
			defer wg3.Done()
			// Каждая горутина делает минимальную работу
			_ = 42
		}()
	}

	wg3.Wait()
	elapsed := time.Since(start)

	fmt.Printf("  Запущено и завершено %d горутин за %v\n", numGoroutines, elapsed)
	fmt.Printf("  Текущее кол-во горутин: %d\n", runtime.NumGoroutine())
	fmt.Printf("  GOMAXPROCS (логических процессоров): %d\n", runtime.GOMAXPROCS(0))
	fmt.Printf("  Кол-во ядер CPU: %d\n", runtime.NumCPU())
	fmt.Println()

	// =====================================================
	// Пример 5: Информация о планировщике
	// =====================================================
	fmt.Println("=== Пример 5: Информация о рантайме ===")
	fmt.Printf("  NumCPU:       %d (физических/логических ядер)\n", runtime.NumCPU())
	fmt.Printf("  GOMAXPROCS:   %d (макс. кол-во одновременно работающих потоков ОС для Go-кода)\n", runtime.GOMAXPROCS(0))
	fmt.Printf("  NumGoroutine: %d (текущих горутин, включая main)\n", runtime.NumGoroutine())
}

// sayHello — именованная функция для запуска как горутина.
func sayHello(wg *sync.WaitGroup, name string) {
	defer wg.Done()
	fmt.Printf("  Привет из %s!\n", name)
}

// deadGoroutineDemo — демонстрация того, что горутины умирают с main.
// ВНИМАНИЕ: эта функция вызывает os.Exit неявно (через завершение main).
// Чтобы увидеть эффект — вызовите её и закомментируйте весь остальной код в main().
func deadGoroutineDemo() {
	fmt.Println("main: запускаю горутину, которая хочет напечатать 5 сообщений...")

	go func() {
		for i := range 5 {
			fmt.Printf("  горутина: сообщение %d\n", i)
			time.Sleep(100 * time.Millisecond)
		}
		fmt.Println("  горутина: я закончила!") // скорее всего, никогда не напечатается
	}()

	// main засыпает лишь на 250ms — горутина не успеет закончить
	time.Sleep(250 * time.Millisecond)
	fmt.Println("main: завершаюсь! Горутина умрёт, не закончив работу.")
	// После этого программа завершится, горутина будет убита.
}
