/*
=== ЗАКРЫТИЕ КАНАЛОВ И ИТЕРАЦИЯ (CLOSE & RANGE) ===

close(ch) — сигнализирует, что больше значений в канал отправляться не будет.

Правила close:
  1. Закрывать канал должен ТОЛЬКО отправитель, никогда получатель.
     Причина: получатель не знает, есть ли ещё отправители.
  2. Закрытие уже закрытого канала → panic: "close of closed channel"
  3. Закрытие nil-канала → panic: "close of nil channel"
  4. Отправка в закрытый канал → panic: "send on closed channel"

Чтение из закрытого канала:
  val := <-ch        → возвращает оставшиеся буферизованные значения, затем нулевое значение типа
  val, ok := <-ch    → ok == false, если канал закрыт И пуст

for val := range ch:
  Идиоматичный способ читать все значения из канала.
  Цикл автоматически завершается, когда канал закрыт и все значения прочитаны.
  Без close() — range заблокируется навсегда (deadlock).

Паттерн "close как broadcast":
  close(ch) разблокирует ВСЕХ ожидающих получателей одновременно.
  Это эффективнее, чем отправлять N сигналов для N горутин.
  Идиоматично: done := make(chan struct{}); close(done) — "всем стоп!"
*/
package main

import (
	"fmt"
	"sync"
	"time"
)

func main() {
	// =====================================================
	// Пример 1: Базовое закрытие канала
	// =====================================================
	fmt.Println("=== Пример 1: Базовое закрытие канала ===")

	ch := make(chan int, 5)
	for i := range 5 {
		ch <- i * 10
	}
	close(ch) // больше не будем отправлять

	// Чтение из закрытого канала: сначала буферизованные значения, потом нулевые
	for range 7 { // читаем 7 раз, хотя отправили 5
		val, ok := <-ch
		fmt.Printf("  val=%d, ok=%v\n", val, ok)
		// Первые 5: ok=true, значения 0,10,20,30,40
		// Последние 2: ok=false, val=0 (нулевое значение int)
	}
	fmt.Println()

	// =====================================================
	// Пример 2: for-range по каналу
	// =====================================================
	fmt.Println("=== Пример 2: for-range по каналу ===")

	words := make(chan string)
	go func() {
		defer close(words) // ВАЖНО: без close() range заблокируется навсегда!
		for _, w := range []string{"Привет", "мир", "Go", "каналы"} {
			words <- w
		}
	}()

	// range автоматически завершится при закрытии канала
	fmt.Print("  Слова: ")
	for w := range words {
		fmt.Printf("[%s] ", w)
	}
	fmt.Println()
	fmt.Println()

	// =====================================================
	// Пример 3: val, ok := <-ch — проверка закрытия
	// =====================================================
	fmt.Println("=== Пример 3: Проверка ok для определения закрытия ===")

	dataCh := make(chan string, 2)
	dataCh <- "данные-1"
	dataCh <- "данные-2"
	close(dataCh)

	for {
		val, ok := <-dataCh
		if !ok {
			fmt.Println("  Канал закрыт и пуст, выходим из цикла.")
			break
		}
		fmt.Printf("  Получено: %q (ok=%v)\n", val, ok)
	}
	fmt.Println()

	// =====================================================
	// Пример 4: Закрытие как broadcast-сигнал
	// =====================================================
	fmt.Println("=== Пример 4: close() как broadcast (сигнал всем горутинам) ===")

	done := make(chan struct{}) // канал-сигнал для остановки
	var wg sync.WaitGroup

	// Запускаем 5 воркеров, каждый ждёт сигнала done
	for i := range 5 {
		wg.Add(1)
		go func() {
			defer wg.Done()
			fmt.Printf("  воркер %d: жду сигнала остановки...\n", i)
			<-done // блокируется до close(done)
			fmt.Printf("  воркер %d: получил сигнал, завершаюсь!\n", i)
		}()
	}

	time.Sleep(200 * time.Millisecond)
	fmt.Println("  main: отправляю broadcast-сигнал остановки (close)...")
	close(done) // ОДИН close разблокирует ВСЕ 5 горутин одновременно!
	wg.Wait()
	fmt.Println("  main: все воркеры завершились.")
	fmt.Println()

	// =====================================================
	// Пример 5: Паники при неправильном использовании close
	// =====================================================
	fmt.Println("=== Пример 5: Паники при неправильном использовании ===")

	// 5a: Закрытие уже закрытого канала → panic
	fmt.Println("  5a. Закрытие уже закрытого канала:")
	func() {
		defer func() {
			if r := recover(); r != nil {
				fmt.Printf("      ПАНИКА перехвачена: %v\n", r)
			}
		}()
		panicCh := make(chan int)
		close(panicCh)
		close(panicCh) // panic!
	}()

	// 5b: Закрытие nil-канала → panic
	fmt.Println("  5b. Закрытие nil-канала:")
	func() {
		defer func() {
			if r := recover(); r != nil {
				fmt.Printf("      ПАНИКА перехвачена: %v\n", r)
			}
		}()
		var nilCh chan int
		close(nilCh) // panic!
	}()

	// 5c: Отправка в закрытый канал → panic
	fmt.Println("  5c. Отправка в закрытый канал:")
	func() {
		defer func() {
			if r := recover(); r != nil {
				fmt.Printf("      ПАНИКА перехвачена: %v\n", r)
			}
		}()
		sendCh := make(chan int, 1)
		close(sendCh)
		sendCh <- 42 // panic!
	}()
	fmt.Println()

	// =====================================================
	// Пример 6: Практический паттерн — генератор с close
	// =====================================================
	fmt.Println("=== Пример 6: Генератор чисел Фибоначчи ===")

	fibs := fibonacci(10) // первые 10 чисел Фибоначчи

	fmt.Print("  Фибоначчи: ")
	for f := range fibs {
		fmt.Printf("%d ", f)
	}
	fmt.Println()
	fmt.Println()

	// =====================================================
	// Пример 7: Множественные отправители, один получатель
	// =====================================================
	fmt.Println("=== Пример 7: Множественные отправители ===")
	fmt.Println("  Правило: если несколько отправителей — НЕ закрывайте канал из отправителя!")
	fmt.Println("  Используйте sync.WaitGroup + отдельную горутину для закрытия.")

	results := make(chan string)
	var wg2 sync.WaitGroup

	// 3 отправителя
	for i := range 3 {
		wg2.Add(1)
		go func() {
			defer wg2.Done()
			for j := range 3 {
				results <- fmt.Sprintf("отправитель-%d: сообщение-%d", i, j)
			}
			// НЕ закрываем канал здесь! Другие отправители ещё работают.
		}()
	}

	// Отдельная горутина ждёт всех отправителей и закрывает канал
	go func() {
		wg2.Wait()
		close(results) // безопасно: все отправители гарантированно закончили
	}()

	// Получатель читает через range
	count := 0
	for msg := range results {
		count++
		fmt.Printf("  %s\n", msg)
	}
	fmt.Printf("  Всего получено сообщений: %d\n", count)

	fmt.Println("\n=== Все примеры завершены ===")
}

// fibonacci — генератор первых n чисел Фибоначчи.
// Возвращает receive-only канал, закрывает его после последнего числа.
func fibonacci(n int) <-chan int {
	out := make(chan int)
	go func() {
		defer close(out)
		a, b := 0, 1
		for range n {
			out <- a
			a, b = b, a+b
		}
	}()
	return out
}
