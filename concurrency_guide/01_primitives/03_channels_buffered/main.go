/*
=== БУФЕРИЗОВАННЫЕ КАНАЛЫ (BUFFERED CHANNELS) ===

Создание: ch := make(chan T, capacity)

Буферизованный канал работает как очередь FIFO фиксированного размера:
  - Отправка (ch <- val) НЕ блокируется, пока в буфере есть место.
  - Отправка БЛОКИРУЕТСЯ, когда буфер полон (len == cap).
  - Получение (val := <-ch) НЕ блокируется, пока в буфере есть данные.
  - Получение БЛОКИРУЕТСЯ, когда буфер пуст (len == 0).

Полезные функции:
  - len(ch) — текущее кол-во элементов в буфере
  - cap(ch) — ёмкость буфера (задана при создании)

Когда использовать буферизованные каналы:
  ✓ Когда производитель и потребитель работают с разной скоростью (сглаживание пиков)
  ✓ Как семафор для ограничения параллелизма
  ✓ Когда нужно "fire and forget" для N сообщений (буфер >= N)
  ✗ НЕ используйте как "ускоритель" по умолчанию — начинайте с небуферизованных каналов

Небуферизованный vs Буферизованный:
  make(chan T)    — рандеву, синхронный обмен. Гарантирует, что получатель УЖЕ обработал данные.
  make(chan T, N) — асинхронный до N элементов. Отправитель может уйти, не дожидаясь получателя.
*/
package main

import (
	"fmt"
	"sync"
	"time"
)

func main() {
	// =====================================================
	// Пример 1: Базовая работа с буферизованным каналом
	// =====================================================
	fmt.Println("=== Пример 1: Базовые операции ===")

	ch := make(chan string, 3) // буфер на 3 элемента

	// Все три отправки НЕ блокируются — буфер не полон
	ch <- "первый"
	ch <- "второй"
	ch <- "третий"

	fmt.Printf("  После 3 отправок: len=%d, cap=%d\n", len(ch), cap(ch))

	// Читаем в порядке FIFO
	fmt.Printf("  Получено: %s\n", <-ch)
	fmt.Printf("  Получено: %s\n", <-ch)
	fmt.Printf("  Получено: %s\n", <-ch)
	fmt.Printf("  После чтения:   len=%d, cap=%d\n", len(ch), cap(ch))
	fmt.Println()

	// =====================================================
	// Пример 2: Неблокирующая отправка, пока есть место
	// =====================================================
	fmt.Println("=== Пример 2: Отправка не блокируется, пока буфер не полон ===")

	bufCh := make(chan int, 5)
	start := time.Now()

	for i := range 5 {
		bufCh <- i // ни одна не блокируется — буфер вмещает 5
		fmt.Printf("  Отправлено %d (len=%d, cap=%d) за %v\n", i, len(bufCh), cap(bufCh), time.Since(start))
	}

	fmt.Println("  Все 5 отправок выполнены мгновенно (без блокировки).")
	// Вычитываем, чтобы канал не утёк
	for range 5 {
		<-bufCh
	}
	fmt.Println()

	// =====================================================
	// Пример 3: Блокировка при полном буфере
	// =====================================================
	fmt.Println("=== Пример 3: Блокировка при полном буфере ===")

	fullCh := make(chan int, 2)
	fullCh <- 1
	fullCh <- 2
	// Буфер полон (len=2, cap=2). Следующая отправка заблокируется.

	go func() {
		time.Sleep(500 * time.Millisecond)
		val := <-fullCh // освобождаем место через 500ms
		fmt.Printf("  горутина: прочитала %d, освободила место\n", val)
	}()

	fmt.Println("  main: буфер полон, следующая отправка заблокируется...")
	startBlock := time.Now()
	fullCh <- 3 // блокируется, пока горутина не прочитает
	fmt.Printf("  main: отправка разблокирована через %v\n", time.Since(startBlock))
	// Вычитываем остаток
	<-fullCh
	<-fullCh
	fmt.Println()

	// =====================================================
	// Пример 4: len() и cap()
	// =====================================================
	fmt.Println("=== Пример 4: len() и cap() ===")

	infoCh := make(chan int, 10)
	fmt.Printf("  Пустой канал:  len=%d, cap=%d\n", len(infoCh), cap(infoCh))

	for i := range 7 {
		infoCh <- i
	}
	fmt.Printf("  После 7 записей: len=%d, cap=%d\n", len(infoCh), cap(infoCh))

	for range 3 {
		<-infoCh
	}
	fmt.Printf("  После 3 чтений:  len=%d, cap=%d\n", len(infoCh), cap(infoCh))

	// Очищаем канал
	for range 4 {
		<-infoCh
	}
	fmt.Println()

	// =====================================================
	// Пример 5: Буферизованный канал как семафор
	// =====================================================
	fmt.Println("=== Пример 5: Канал как семафор (ограничение параллелизма) ===")

	// Семафор на 3: одновременно работают не более 3 горутин
	const maxConcurrent = 3
	sem := make(chan struct{}, maxConcurrent)

	var wg sync.WaitGroup
	for i := range 10 {
		wg.Add(1)
		go func() {
			defer wg.Done()

			sem <- struct{}{} // захватываем слот (блокируемся, если все 3 заняты)
			defer func() { <-sem }() // освобождаем слот

			fmt.Printf("  задача %d: выполняюсь (активных слотов: %d из %d)\n",
				i, len(sem), cap(sem))
			time.Sleep(200 * time.Millisecond) // имитация работы
		}()
	}

	wg.Wait()
	fmt.Println("  Все 10 задач выполнены с ограничением параллелизма =", maxConcurrent)
	fmt.Println()

	// =====================================================
	// Пример 6: Практический паттерн — сбор результатов
	// =====================================================
	fmt.Println("=== Пример 6: Сбор результатов через буферизованный канал ===")

	const numWorkers = 5
	// Буфер = кол-во воркеров, чтобы все могли отправить без блокировки
	results := make(chan string, numWorkers)

	for i := range numWorkers {
		go func() {
			time.Sleep(time.Duration(i*50) * time.Millisecond) // разное время работы
			results <- fmt.Sprintf("результат от воркера %d", i)
		}()
	}

	// Собираем все результаты
	for range numWorkers {
		fmt.Printf("  %s\n", <-results)
	}
	fmt.Println()

	// =====================================================
	// Пример 7: Deadlock с буферизованным каналом
	// =====================================================
	fmt.Println("=== Пример 7: Даже буферизованный канал может вызвать deadlock ===")
	fmt.Println("  // ch := make(chan int, 2)")
	fmt.Println("  // ch <- 1")
	fmt.Println("  // ch <- 2")
	fmt.Println("  // ch <- 3  // DEADLOCK: буфер полон, никто не читает!")
	fmt.Println("  Буферизованный канал — это НЕ бесконечная очередь. Когда буфер полон — блокировка.")

	fmt.Println("\n=== Все примеры завершены ===")
}
